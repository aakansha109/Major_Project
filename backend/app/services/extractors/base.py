from abc import ABC, abstractmethod
from datetime import datetime, timezone
from typing import List, Optional, Dict, Any, Tuple
from pydantic import BaseModel, Field, field_validator
import re

from app.models.fact import Fact

class LLMExtractedTriplet(BaseModel):
    """
    Strict validation schema for triplets generated by an LLM.
    Malformed, ungrounded, circular, or unsupported outputs are rejected.
    """
    subject: str = Field(..., description="Subject entity (e.g. 'User', 'Alice')")
    predicate: str = Field(..., description="Temporal relation or attribute name (e.g. 'backend_framework')")
    object: str = Field(..., description="Target entity or attribute value (e.g. 'FastAPI')")
    valid_from: Optional[str] = Field(default=None, description="ISO timestamp or YYYY-MM-DD or None")
    confidence: float = Field(default=0.85, ge=0.0, le=1.0, description="Self-reported confidence score")

    @field_validator("subject", mode="before")
    @classmethod
    def validate_subject(cls, v: Any) -> str:
        if not isinstance(v, str):
            raise ValueError("Subject must be a string")
        s = v.strip().strip(".,;:?!'\" ")
        if not s:
            raise ValueError("Subject cannot be empty")
        if len(s) > 100:
            raise ValueError("Subject exceeds maximum length of 100 characters")
        return s

    @field_validator("predicate", mode="before")
    @classmethod
    def validate_predicate(cls, v: Any) -> str:
        if not isinstance(v, str):
            raise ValueError("Predicate must be a string")
        p = v.strip().lower().replace(" ", "_").strip(".,;:?!'\" ")
        p = re.sub(r"[^a-z0-9_]", "", p)
        if not p:
            raise ValueError("Predicate cannot be empty")
        if len(p) > 60:
            raise ValueError("Predicate exceeds maximum length of 60 characters")
        return p

    @field_validator("object", mode="before")
    @classmethod
    def validate_object(cls, v: Any) -> str:
        if not isinstance(v, str):
            raise ValueError("Object must be a string")
        o = v.strip().strip(".,;:?!'\" ")
        if not o:
            raise ValueError("Object cannot be empty")
        if len(o) > 200:
            raise ValueError("Object exceeds maximum length of 200 characters")
        return o

    @field_validator("valid_from", mode="before")
    @classmethod
    def validate_valid_from(cls, v: Any) -> Optional[str]:
        if not v or str(v).lower() in ["none", "null", ""]:
            return None
        v_str = str(v).strip()
        # Verify valid date or ISO format
        try:
            datetime.fromisoformat(v_str.replace("Z", "+00:00"))
            return v_str
        except Exception:
            # Check YYYY-MM-DD or YYYY
            if re.match(r"^\d{4}-\d{2}-\d{2}$", v_str):
                return f"{v_str}T00:00:00Z"
            elif re.match(r"^\d{4}$", v_str):
                return f"{v_str}-01-01T00:00:00Z"
            raise ValueError(f"Invalid timestamp format: {v_str}")

    def is_valid_triplet(self) -> Tuple[bool, Optional[str]]:
        # Circularity check
        if self.subject.lower() == self.object.lower():
            return False, f"Circular fact rejected: subject '{self.subject}' equals object '{self.object}'"
        # Gibberish check
        if len(self.subject) < 2 or len(self.object) < 2:
            return False, "Subject or object too short to represent meaningful entity"
        return True, None

class ExtractionResult(BaseModel):
    """
    Standardized result contract returned by all extractors.
    Carries full telemetry, token accounting, and decision provenance.
    """
    facts: List[Fact] = Field(default_factory=list)
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    extraction_method: str = Field(..., description="'rule', 'llm', 'hybrid_rule', 'hybrid_llm_fallback', 'rejected'")
    latency_ms: float = Field(default=0.0)
    
    # Token usage & Cost accounting
    input_tokens: Optional[int] = Field(default=None, description="Actual measured input tokens from LLM API")
    output_tokens: Optional[int] = Field(default=None, description="Actual measured output tokens from LLM API")
    total_tokens: int = Field(default=0, description="Total tokens used (0 for rules)")
    tokens_is_measured: bool = Field(default=False, description="True if tokens were directly reported by provider usage object")
    estimated_cost_usd: float = Field(default=0.0, description="Monetary cost calculated on explicit pricing basis")
    cost_pricing_basis: Optional[str] = Field(default=None, description="Pricing rate formula documentation")
    
    # Research decision tracking
    decision_reason: str = Field(..., description="Audit explanation of path chosen and confidence gating outcome")
    fallback_triggered: bool = Field(default=False, description="True if LLM fallback was invoked")
    raw_llm_response: Optional[str] = Field(default=None, description="Raw provider output for auditing")
    validation_errors: List[str] = Field(default_factory=list, description="List of schema validation rejections")

class BaseExtractor(ABC):
    """Common interface for rule-based, LLM-based, and hybrid fact extractors"""

    @abstractmethod
    async def extract(
        self,
        text: str,
        episode_time: datetime,
        default_speaker: str = "User"
    ) -> ExtractionResult:
        """Extract structured facts from text utterance with full provenance and telemetry"""
        pass
